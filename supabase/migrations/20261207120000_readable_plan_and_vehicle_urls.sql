-- Plans and cars get addresses made of words, the way big shops do it:
--
--   /services/clubs/plans/beach-club-membership-1042
--   /vehicles/vehicle/jeep-wrangler-4x4-1007
--
-- instead of /services/clubs/plans/6d258149-6cf5-43d8-a0ce-fa60fcc8dfa0.
--
-- Why "words + short number" and not words alone (as businesses got in
-- 20261127120000_provider_slugs):
--   - plan names repeat across businesses ("Monthly Membership", "Weekly
--     Cleaning"); words alone would need "-2", "-3"… that mean nothing;
--   - plans and cars get renamed. The number is what the address is looked up
--     by; the words are only for people and search engines. After a rename the
--     words change, and every old link still opens — the app and the robot
--     pages see the same number with stale words and send it on (301) to the
--     current words. No history table, no broken shares.
--
-- The uuid (and a legacy plan's own id) keeps working everywhere and is sent on
-- to the words in the same way.

-- ── Words from any name ─────────────────────────────────────────────────────
-- Spanish accents (Roatán), and Ukrainian/Russian Cyrillic transliterated
-- (Тунець → tunets), so a name in any of them gives readable Latin words.
create or replace function public.slugify_text(p_text text)
returns text
language sql
immutable
parallel safe
set search_path = public
as $$
  select nullif(trim(both '-' from left(
    regexp_replace(translate(replace(replace(replace(replace(replace(replace(replace(replace(replace(replace(replace(replace(replace(replace(replace(lower(coalesce(p_text, '')), 'щ', 'shch'), 'ж', 'zh'), 'х', 'kh'), 'ц', 'ts'), 'ч', 'ch'), 'ш', 'sh'), 'ю', 'iu'), 'я', 'ia'), 'є', 'ie'), 'ß', 'ss'), 'æ', 'ae'), 'œ', 'oe'), 'ø', 'o'), '&', '-and-'), '+', '-plus-'),
      'áàâäãåéèêëíìîïóòôöõúùûüñçýабвгґдезиіїйклмнопрстуфыэёъь''’',
      'aaaaaaeeeeiiiiooooouuuuncyabvhgdezyiiiklmnoprstufyee'),
      '[^a-z0-9]+', '-', 'g'), 60)), '');
$$;

comment on function public.slugify_text(text) is
  'Lower-case Latin words joined by hyphens, from a name in English, Spanish, Ukrainian or Russian. At most 60 characters. Used for the words in public addresses.';

-- ── Plans ───────────────────────────────────────────────────────────────────
-- Every plan has a provider_plans row (legacy food/cleaning/beach plans are
-- mirrored there), so this one table gives every plan its address.
alter table public.provider_plans
  add column if not exists public_no bigint generated by default as identity (start with 1001);
alter table public.provider_plans add column if not exists slug text;

create unique index if not exists provider_plans_public_no_key on public.provider_plans (public_no);

update public.provider_plans set slug = coalesce(public.slugify_text(name), 'plan')
 where slug is distinct from coalesce(public.slugify_text(name), 'plan');

-- The words follow the name: renaming is safe because lookups use the number.
create or replace function public.fill_slug_from_name()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.slug := coalesce(public.slugify_text(new.name), TG_ARGV[0]);
  return new;
end;
$$;
revoke execute on function public.fill_slug_from_name() from public, anon, authenticated;

drop trigger if exists provider_plans_fill_slug on public.provider_plans;
create trigger provider_plans_fill_slug
  before insert or update of name, slug on public.provider_plans
  for each row execute function public.fill_slug_from_name('plan');

comment on column public.provider_plans.public_no is
  'The short number in the plan''s public address (/services/<service>/plans/<slug>-<public_no>). Never changes; the address is looked up by it.';
comment on column public.provider_plans.slug is
  'The words in the plan''s public address, made from the name and kept in step with it. Not unique — public_no is.';

